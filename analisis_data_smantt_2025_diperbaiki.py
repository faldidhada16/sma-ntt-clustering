# ------------------------------------------------------------ Jarak Gower
def gower(Xn, Xc, idx=None):
    rng = Xn.max(0) - Xn.min(0); rng[rng == 0] = 1
    num = np.abs(Xn[:, None, :] - Xn[None, :, :]) / rng
    cat = (Xc[:, None, :] != Xc[None, :, :]).astype(float)
    return (num.sum(2) + cat.sum(2)) / (Xn.shape[1] + Xc.shape[1])

