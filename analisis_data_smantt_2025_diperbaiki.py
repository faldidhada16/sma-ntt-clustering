def n_berpindah(acuan, label):
    """Jumlah wilayah yang berpindah klaster setelah label diselaraskan (algoritma Hungaria)."""
    ka, kb = np.unique(acuan), np.unique(label)
    m = np.array([[np.sum((acuan == a) & (label == b)) for b in kb] for a in ka])
    r, c = linear_sum_assignment(-m)
    return int(len(acuan) - m[r, c].sum())

rows = []
