# ------------------------------------------------------------ 4. Friedman + Nemenyi (Demsar, 2006)
names = list(MODELS)
M = np.column_stack([FS[nm]["Balanced_Acc"].values for nm in names])
fr = stats.friedmanchisquare(*M.T)
ranks = pd.DataFrame(M).rank(axis=1, ascending=False).mean().values
kq = len(names); N = M.shape[0]
q05 = {2: 1.960, 3: 2.343, 4: 2.569, 5: 2.728, 6: 2.850, 7: 2.949, 8: 3.031}[kq]
