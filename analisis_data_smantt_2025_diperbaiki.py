# ------------------------------------------------------------ K-Prototypes (Huang, 1998)
def kprototypes(Z, C, k, gamma, n_init=30, max_iter=100, rng=None):
    rng = rng or np.random.default_rng(SEED)
    best = (np.inf, None)
    m = len(Z)
    for _ in range(n_init):
        _, uidx = np.unique(np.column_stack([Z, C]), axis=0, return_index=True)
        idx = rng.choice(uidx, k, replace=False)      # prototipe awal dari titik unik
        P, Q = Z[idx].copy(), C[idx].copy()
        lab = None
        for _ in range(max_iter):
            cost = ((Z[:, None, :] - P[None]) ** 2).sum(2) + gamma * (C[:, None, :] != Q[None]).sum(2)
            new = cost.argmin(1)
            for j in range(k):                       # klaster kosong -> titik terjauh dari klaster berukuran > 1
                if not (new == j).any():
                    sz = np.bincount(new, minlength=k)
                    cand = np.where(sz[new] > 1)[0]
                    far = cand[cost[cand, new[cand]].argmax()]; new[far] = j
            if lab is not None and (new == lab).all(): break
            lab = new
            for j in range(k):
                mem = lab == j
                if not mem.any(): continue
                P[j] = Z[mem].mean(0)
                for c in range(C.shape[1]):
                    v, cnt = np.unique(C[mem, c], return_counts=True); Q[j, c] = v[cnt.argmax()]
        tot = (((Z - P[lab]) ** 2).sum() + gamma * (C != Q[lab]).sum())
        if tot < best[0]: best = (tot, lab.copy())
    return best[1], best[0]

