def tuned(est, grid):
    return GridSearchCV(est, grid, scoring="balanced_accuracy", cv=inner, n_jobs=-1, refit=True)

def _auc(y, s):
    if s is None: return np.nan
    try: return roc_auc_score(y, s, multi_class="ovr", labels=LAB)
    except ValueError: return np.nan

def metrics(y, p, s):
    return dict(Accuracy=accuracy_score(y, p), Balanced_Acc=balanced_accuracy_score(y, p),
                F1_macro=f1_score(y, p, average="macro"),
                Kappa=cohen_kappa_score(y, p), MCC=matthews_corrcoef(y, p),
                ROC_AUC=_auc(y, s))

