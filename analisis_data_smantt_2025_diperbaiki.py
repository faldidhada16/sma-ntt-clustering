# ------------------------------------------------------------ PAM (Kaufman & Rousseeuw)
def pam(D, k, max_iter=100):
    m = len(D)
    med = [int(D.sum(1).argmin())]                   # BUILD
    while len(med) < k:
        dmin = D[:, med].min(1)
        gain = [(np.maximum(dmin - D[:, c], 0).sum() if c not in med else -1) for c in range(m)]
        med.append(int(np.argmax(gain)))
    cost = D[:, med].min(1).sum()
    for _ in range(max_iter):                         # SWAP
        best = (cost, None)
        for i in range(k):
            for h in range(m):
                if h in med: continue
                trial = med.copy(); trial[i] = h
                c = D[:, trial].min(1).sum()
                if c < best[0] - 1e-12: best = (c, trial)
        if best[1] is None: break
        cost, med = best
    lab = D[:, med].argmin(1)
    return lab, np.array(med), cost

# ------------------------------------------------------------ Metrik internal
def internal(labels, D, Z):
    lab = np.asarray(labels); keep = lab >= 0
    u = np.unique(lab[keep])
    if len(u) < 2 or keep.sum() <= len(u):
        return dict(silhouette=np.nan, silhouette_cov=np.nan, cakupan=np.nan, DBI=np.nan, CH=np.nan, DBI_full=np.nan, CH_full=np.nan)
    Dk = D[np.ix_(keep, keep)]
    sil = silhouette_score(Dk, lab[keep], metric="precomputed")
    full = lab.copy(); nz = np.where(lab < 0)[0]
    full[nz] = lab.max() + 1 + np.arange(len(nz))     # noise sebagai klaster tunggal (cakupan seluruh 22 kabupaten/kota)
    return dict(silhouette=sil, silhouette_cov=sil * keep.mean(), cakupan=keep.mean(),
                DBI=davies_bouldin_score(Z[keep], lab[keep]),
                CH=calinski_harabasz_score(Z[keep], lab[keep]),
                DBI_full=davies_bouldin_score(Z, full), CH_full=calinski_harabasz_score(Z, full))

# ------------------------------------------------------------ Kestabilan (Hennig 2007)
def stability(fit, labels0, scheme="bootstrap", B=B, seed=SEED):
    rng = np.random.default_rng(seed)
    lab0 = np.asarray(labels0)
    clusters = [c for c in np.unique(lab0) if c >= 0]
    J = {c: [] for c in clusters}; ARI = []
    for b in range(B):
        if scheme == "bootstrap":
            s = rng.choice(n, n, replace=True)
        else:
            s = rng.choice(n, int(round(0.8 * n)), replace=False)
        lb = fit(s, rng)                              # label untuk tiap anggota sampel s
        uniq, first = np.unique(s, return_index=True)
        lu = lb[first]                                # label per titik unik
        o = lab0[uniq]
        ARI.append(adjusted_rand_score(o, lu))
        for c in clusters:
            A = set(uniq[o == c])
            if not A: continue
            best = 0.0
            for g in np.unique(lu):
                if g < 0: continue                    # noise DBSCAN bukan klaster
                Bset = set(uniq[lu == g])
                best = max(best, len(A & Bset) / len(A | Bset))
            J[c].append(best)
    Jm = {int(c): float(np.mean(v)) for c, v in J.items()}
    return Jm, float(np.mean(ARI)), {int(c): v for c, v in J.items()}, ARI

